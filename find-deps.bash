#!/bin/bash

# Проверяем, передан ли аргумент
if [ -z "$1" ]; then
  echo "Использование: $0 <путь_к_папке>"
  echo "Пример: $0 apps/api-gateway/src"
  exit 1
fi

TARGET_DIR="$1"

# Проверяем, существует ли папка
if [ ! -d "$TARGET_DIR" ]; then
  echo "Ошибка: Папка '$TARGET_DIR' не существует."
  exit 1
fi

echo "🔍 Анализ зависимостей в '$TARGET_DIR'..."
echo "------------------------------------------------"

# 1. Ищем конструкции import, from и require
# 2. Вытаскиваем только содержимое кавычек
# 3. Удаляем сами кавычки
# 4. Фильтруем относительные пути (.), алиасы (@/) и локальные либы (@clarte/)
# 5. Обрезаем глубокие пути, оставляя только имя пакета (с учетом scoped пакетов типа @nestjs/core)
# 6. Сортируем и убираем дубликаты
grep -rohE "(from|import|require\s*\()\s*['\"][^'\"]+['\"]" "$TARGET_DIR" |
  grep -oE "['\"][^'\"]+['\"]" |
  tr -d "'\"" |
  grep -vE "^(\.|\.\.|@/|@clarte/)" |
  awk -F/ '{if($1 ~ /^@/) print $1"/"$2; else print $1}' |
  sort -u

echo "------------------------------------------------"
echo "✅ Готово! Проверьте, все ли эти пакеты есть в package.json"
